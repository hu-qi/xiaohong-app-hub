const char *xh_tls_ca_pem(void)
{
    return XH_TLS_CA_PEM;
}

bool xh_tls_apply(struct mg_connection *c, const char *url)
{
    if (c == NULL || url == NULL || url[0] == '\0') {
        return false;
    }

    /* 仅 TLS 系（https/wss/mqtts/ssl/tls/tcps）需要挂 TLS；http/ws 保持明文 */
    if (!mg_url_is_ssl(url)) {
        return false;
    }

    /*
     * name 必须填：mongoose 内建 TLS 用它做 SNI，并在开户前校验证书 SAN/CN。
     * mg_url_host() 返回的是 url 内部切片，url 由调用方持有（ctx->url 等），
     * mg_tls_init() 会立即把 hostname 拷入 tls->hostname，故此处无生命周期问题。
     */
    struct mg_tls_opts opts;
    memset(&opts, 0, sizeof(opts));
    opts.ca = mg_str(xh_tls_ca_pem());
    opts.cert = mg_str_n(NULL, 0);
    opts.key = mg_str_n(NULL, 0);
    opts.name = mg_url_host(url);
    opts.skip_verification = 0; /* 严格校验：链 + 主机名 */

    if (opts.name.len == 0) {
        /* 无主机名则无法做 SNI/主机名校验，视为失败，让上层走错误路径 */
        mg_error(c, "tls: no hostname");
        return false;
    }

    mg_tls_init(c, &opts);
    return true;
}
